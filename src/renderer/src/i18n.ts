const dict: Record<Lang, Record<Key, string>> = {en, sq, mk}
const asLang = (l: string): Lang => (l === 'sq' || l === 'mk' ? l : 'en')

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
    const s = dict[lang][key] || en[key]
    return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s
}

let current: Lang = 'en'
export const setLang = (l: string): void => {
    current = asLang(l)
}
export const normalizeLang = asLang

// Messages thrown by the core are in English; known ones are shown in the chosen language.
const ERRORS: [string, Key][] = [
    ['Wrong PIN', 'errWrongPin'], ['Only an admin can do this', 'errAdminOnly'], ['Select an employee first', 'errSelectEmployee'],
    ['This order is already closed and cannot be changed', 'errClosed'], ['The order is empty', 'errEmpty'],
    ['Product not available', 'errProduct'], ['Product out of stock', 'errOutOfStock'], ['Card payments are turned off', 'errCardOff'], ['Employee not found', 'errEmployee'],
    ['Keep at least one active admin', 'errLastAdmin'], ['This table has an open order', 'errTableBusy'],
    ['Only an admin can open older orders', 'errOlder'], ['This file is not a valid Café Manager backup', 'errBackup']
]

export function errorText(m: string): string {
    const hit = ERRORS.find(([en]) => en === m)
    if (hit) return translate(current, hit[1])
    const lock = /^Too many wrong PINs\. Try again in (\d+) seconds\.$/.exec(m)
    return lock ? translate(current, 'errLocked', {n: lock[1]}) : m
}

export const LangCtx = createContext<Lang>('en')

export function useT(): (key: Key, vars?: Record<string, string | number>) => string {
    const lang = useContext(LangCtx)
    return useCallback((key, vars) => translate(lang, key, vars), [lang])
}
